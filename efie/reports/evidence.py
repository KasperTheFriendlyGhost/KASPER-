"""Human-readable evidence summary (``docs/evidence/EVIDENCE.md``) from the JSON results.

Only aggregate statistics are written here; no prices or bars, so the file can be
committed without redistributing licensed market data.
"""

from __future__ import annotations

import json

from efie.paths import EVIDENCE_DIR


def _load(name):
    p = EVIDENCE_DIR / name
    return json.loads(p.read_text()) if p.exists() else None


def _ci(c, f="{:+.4f}"):
    return f"[{f.format(c[0])}, {f.format(c[1])}]"


def write_evidence() -> str:
    val, hyp, bt, dg = (_load(n) for n in ("validation.json", "hypotheses.json", "backtest.json", "diagnostics.json"))
    L = ["# EFIE milestone 1 — evidence", ""]
    L.append("Generated by `python -m efie evidence` from the JSON files in this folder. "
             "All figures are out-of-sample or event-study statistics on real data; no bar data is stored here.")
    if val:
        L.append("")
        L.append(f"Data snapshot: {val['snapshot']}.")
        L.append("")
        L.append("## 1. Forecast validation (purged expanding-window walk-forward)")
        L.append("")
        L.append("| Horizon | OOS window | n | Model | Brier skill vs climatology (95% CI) | AUC | OOS R² (95% CI) | 80% interval coverage (climatology) | Interval score vs climatology | Gate (dir / ret / int) |")
        L.append("|---|---|---|---|---|---|---|---|---|---|")
        for h, r in val["horizons"].items():
            for m in ("tech", "tech_fund"):
                s = r["scores"][m]
                g = r["gate"][m]
                gv = " / ".join("✓" if g[k]["verdict"] == "VALIDATED" else "✕" for k in ("direction", "expected_return", "interval"))
                L.append(
                    f"| {h} | {s['start'][:10]} → {s['end'][:10]} | {s['n']} | {m} | {s['bss']:+.4f} {_ci(s['bss_ci'])} | {s['auc']:.3f} "
                    f"| {s['r2_oos']:+.4f} {_ci(s['r2_ci'])} | {s['coverage']:.3f} ({s.get('coverage_clim', float('nan')):.3f}) "
                    f"| {s.get('interval_score', float('nan')):.5f} vs {s.get('interval_score_clim', float('nan')):.5f} | {gv} |"
                )
        L.append("")
        L.append("Incremental value of the fundamentals (paired Brier difference, positive = fundamentals help):")
        L.append("")
        for h, r in val["horizons"].items():
            i = r["incremental"]["tech_fund_vs_tech"]
            L.append(f"- **{h}**: {i['mean_diff']:+.6f} {_ci(i['ci'], '{:+.6f}')}, one-sided p = {i['p_value_one_sided']:.3f}")
        L.append("")
        L.append("Year-by-year Brier skill of the EFIE model (`tech_fund`):")
        L.append("")
        for h, r in val["horizons"].items():
            L.append(f"- {h}: " + ", ".join(f"{x['period'][:4]} {x['bss']:+.3f}" for x in r["by_year"]["tech_fund"]))
    if hyp:
        L.append("")
        L.append("## 2. Pre-registered hypothesis tests (Spearman ρ, moving-block bootstrap CI)")
        L.append("")
        L.append("| Test | n | ρ | 95% CI | p | Holm p | Significant |")
        L.append("|---|---|---|---|---|---|---|")
        for grp in ("sanity", "family"):
            for k, t in hyp[grp].items():
                tag = " *(sanity, post hoc)*" if t.get("post_hoc") else (" *(sanity)*" if grp == "sanity" else "")
                ph = f"{t['p_holm']:.3f}" if "p_holm" in t else "—"
                sig = ("yes" if t.get("significant_after_holm") else "no") if grp == "family" else "—"
                L.append(f"| {k}{tag} | {t['n']} | {t['rho']:+.3f} | {_ci(t['ci'], '{:+.3f}')} | {t['p']:.3f} | {ph} | {sig} |")
    if bt:
        L.append("")
        L.append("## 3. Overlay backtests (MCL, 1 contract, after costs)")
        c = bt["costs"]
        L.append("")
        L.append(f"Costs: ${c['commission_per_side_usd']:.2f} commission + {c['slippage_ticks_per_side']:g} tick (${c['tick_value_usd']:.2f}) slippage per side; "
                 f"rolls pay a round trip; every variant also re-run at {c['stress_multiplier']:g}× costs. "
                 f"Windows: hourly from {bt['window']['hourly_start'][:16]}, daily from {bt['window']['daily_start'][:10]} (the EFIE out-of-sample period).")
        L.append("")
        L.append("| Strategy | Variant | Net USD | Sharpe | Max DD USD | Contracts traded | Net USD at stress costs |")
        L.append("|---|---|---|---|---|---|---|")
        for s, vs in bt["strategies"].items():
            for v, r in vs.items():
                a = r["costs_1x"]
                st = next(r[k] for k in r if k.startswith("costs_") and k != "costs_1x" and "excluding" not in k)
                L.append(f"| {s} | {v} | {a['net_usd']:,.0f} | {a['sharpe_annual']:+.2f} | {a['max_drawdown_usd']:,.0f} | {a['contracts_traded']:,.0f} | {st['net_usd']:,.0f} |")
        L.append("")
        L.append("| Overlay test | Δ USD / session (95% CI) | Δ Sharpe (95% CI) | Holm p | Significant |")
        L.append("|---|---|---|---|---|")
        for k, t in bt["tests"].items():
            L.append(f"| {k} | {t['mean_diff_usd_per_session']:+.2f} {_ci(t['ci'], '{:+.2f}')} | {t['sharpe_diff']:+.2f} {_ci(t['sharpe_diff_ci'], '{:+.2f}')} | {t['p_holm']:.3f} | {'yes' if t['significant_after_holm'] else 'no'} |")
        L.append("")
        L.append("`REF` strategies are reference baselines written for this test harness, not your MCL strategies.")
    if dg:
        L.append("")
        L.append("## 4. Data integrity")
        L.append("")
        L.append("| Series | Interval | Rows | With consensus | First | Last |")
        L.append("|---|---|---|---|---|---|")
        for x in dg["coverage"]:
            L.append(f"| {x['series']} | {x['interval']} | {x['rows']} | {x.get('with_consensus', '')} | {x['first'][:16]} | {x['last'][:16]} |")
        L.append("")
        w = dg["eia_weeks"]
        L.append(f"EIA weeks without a crude release since 2015: {', '.join(w['missing_weeks']) or 'none'}; "
                 f"weeks with two releases: {', '.join(w['weeks_with_two_releases']) or 'none'} (delayed reports published the following week).")
        rh, rd = dg["rolls_hourly"], dg["rolls_daily"]
        L.append("")
        L.append(f"Roll reconstruction — hourly: {rh['by_method']}, detected offsets vs CME last trade (business days): {rh['detected_offset_bd']}; "
                 f"daily: {rd['by_method']}, detected offsets: {rd['detected_offset_bd']}; daily and hourly agree on {dg['rolls_daily_vs_hourly_same_date']} contracts.")
        ra = dg.get("release_alignment_hourly") or {}
        if ra:
            L.append("")
            L.append(f"Stated EIA release times (ET): {ra['release_times_et']}.")
            L.append("Median |return| and relative volume by hourly bar offset from the stated release bar: "
                     + "; ".join(f"{int(p['offset_bars']):+d}: {p['abs_ret']:.4f} / {p['rel_volume']:.2f}×" for p in ra["profile"]))
    out = EVIDENCE_DIR / "EVIDENCE.md"
    out.write_text("\n".join(L) + "\n")
    # Provenance: which raw files the evidence came from (requests and SHA-256 only, no data).
    from efie.ingest.stage import read_manifest

    entries = sorted(read_manifest(), key=lambda e: e["dataset"])
    (EVIDENCE_DIR / "data_manifest.jsonl").write_text("".join(json.dumps(e) + "\n" for e in entries))
    return str(out)
